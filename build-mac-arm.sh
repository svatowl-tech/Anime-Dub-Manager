#!/bin/bash
# Скрипт для сборки приложения под macOS ARM (Apple Silicon, M1/M2/M3)
# Данный скрипт автоматически скачивает зависимости и выполняет сборку.

set -e

echo "========================================================="
echo "       Anime Dub Manager - Сборка для macOS ARM64       "
echo "========================================================="

# 1. Проверка наличия Node.js и npm
if ! command -v node &> /dev/null; then
    echo "❌ Ошибка: Node.js не установлен."
    echo "Пожалуйста, установите Node.js (рекомендуется v18+ или v20+) с официального сайта: https://nodejs.org/"
    echo "Или через Homebrew: brew install node"
    exit 1
fi

echo "✅ Node.js найден: $(node -v)"
echo "✅ npm найден: $(npm -v)"

# 2. Установка зависимостей проекта
echo "📦 Шаг 1: Установка npm-зависимостей..."
npm install

# 3. Скачивание и подготовка сайдкаров и бинарных утилит (FFmpeg, модели, WhisperLiveKit)
echo "⚙️ Шаг 2: Подготовка и загрузка зависимостей, FFmpeg SDK и ИИ-сайдкаров..."
node scripts/prepare-sidecars.js

# 4. Генерация метаданных
echo "📝 Шаг 3: Генерация метаданных сборки..."
node scripts/generate-metadata.js

# 5. Сборка фронтенда Vite
echo "🏗️ Шаг 4: Сборка фронтенда (Vite)..."
npx vite build

# 6. Сборка Electron приложения (dmg, zip)
echo "🚀 Шаг 5: Создание установщиков (.dmg, .zip)..."
# Используем флаги --mac и --arm64 для явного указания платформы
npx electron-builder --mac --arm64

echo "========================================================="
echo "✅ Сборка успешно завершена!"
echo "Установочные файлы (DMG) находятся в папке 'out/'"
echo "========================================================="
